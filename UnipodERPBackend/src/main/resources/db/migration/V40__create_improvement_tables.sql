-- FR-010 improvement module ("refinement"): requests for changes, the items asked for, and the
-- submitter's improved versions of a brief.
-- brief_id holds submissions.id (UUID) as a plain value: there is deliberately no foreign key to
-- tables owned by other modules. People are identified by email (api_users.email is VARCHAR(254)).
-- The only foreign keys are between the improvement tables themselves.

CREATE TABLE refinement_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    brief_id UUID NOT NULL,
    cycle INTEGER NOT NULL,
    source VARCHAR(32) NOT NULL,
    guidance_note VARCHAR(2000) NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
    requested_by VARCHAR(254) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL,
    responded_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_refinement_requests PRIMARY KEY (id),
    CONSTRAINT ck_refinement_requests_cycle CHECK (cycle >= 1),
    CONSTRAINT ck_refinement_requests_source CHECK (source IN ('FACT_FINDING', 'COORDINATOR')),
    CONSTRAINT ck_refinement_requests_status CHECK (status IN ('OPEN', 'RESPONDED')),
    CONSTRAINT uq_refinement_requests_brief_cycle UNIQUE (brief_id, cycle)
);

CREATE INDEX ix_refinement_requests_brief_status ON refinement_requests (brief_id, status);

CREATE TABLE refinement_requested_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    request_id BIGINT NOT NULL,
    position INTEGER NOT NULL,
    text VARCHAR(500) NOT NULL,
    CONSTRAINT pk_refinement_requested_changes PRIMARY KEY (id),
    CONSTRAINT ck_refinement_requested_changes_position CHECK (position >= 1),
    CONSTRAINT uq_refinement_requested_changes_request_position UNIQUE (request_id, position),
    CONSTRAINT fk_refinement_requested_changes_request
        FOREIGN KEY (request_id) REFERENCES refinement_requests (id)
);

CREATE TABLE case_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    brief_id UUID NOT NULL,
    version_number INTEGER NOT NULL,
    request_id BIGINT NOT NULL,
    what_changed VARCHAR(2000) NOT NULL,
    submitted_by VARCHAR(254) NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_case_revisions PRIMARY KEY (id),
    CONSTRAINT ck_case_revisions_version_number CHECK (version_number >= 2),
    CONSTRAINT uq_case_revisions_brief_version UNIQUE (brief_id, version_number),
    CONSTRAINT uq_case_revisions_request UNIQUE (request_id),
    CONSTRAINT fk_case_revisions_request
        FOREIGN KEY (request_id) REFERENCES refinement_requests (id)
);

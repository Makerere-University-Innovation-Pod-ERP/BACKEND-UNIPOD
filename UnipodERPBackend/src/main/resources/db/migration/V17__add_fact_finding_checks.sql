CREATE TABLE fact_finding_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    brief_id BIGINT NOT NULL,
    round INTEGER NOT NULL DEFAULT 1 CHECK (round > 0),
    officer_id BIGINT NOT NULL,
    title_clear BOOLEAN,
    title_note VARCHAR(255),
    purpose_clear BOOLEAN,
    purpose_note VARCHAR(255),
    evidence_enough BOOLEAN,
    evidence_note VARCHAR(255),
    relevant_to_hub BOOLEAN,
    relevant_note VARCHAR(255),
    missing_items VARCHAR(2000),
    result VARCHAR(32),
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_fact_finding_checks PRIMARY KEY (id),
    CONSTRAINT uq_fact_finding_checks_brief_round UNIQUE (brief_id, round)
);

CREATE INDEX ix_fact_finding_checks_brief_id ON fact_finding_checks (brief_id);

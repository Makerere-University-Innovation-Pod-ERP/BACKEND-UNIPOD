-- FR-009 review module: settings, reviewer assignments, submitted reviews and follow-up notes.
-- brief_id holds submissions.id (UUID) as a plain value: there is deliberately no foreign key
-- to tables owned by other modules. Reviewer and actor identities are the JWT subject, which
-- is the user's email (api_users.email is VARCHAR(254)).

CREATE TABLE review_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    brief_id UUID NOT NULL,
    round INTEGER NOT NULL DEFAULT 1,
    mode VARCHAR(32) NOT NULL,
    reviews_needed INTEGER NOT NULL,
    due_date DATE,
    set_by VARCHAR(254) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_review_settings PRIMARY KEY (id),
    CONSTRAINT ck_review_settings_round CHECK (round > 0),
    CONSTRAINT ck_review_settings_mode CHECK (mode IN ('PARALLEL', 'SEQUENTIAL')),
    CONSTRAINT ck_review_settings_reviews_needed CHECK (reviews_needed >= 1),
    CONSTRAINT uq_review_settings_brief_round UNIQUE (brief_id, round)
);

CREATE TABLE review_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    brief_id UUID NOT NULL,
    round INTEGER NOT NULL DEFAULT 1,
    reviewer_id VARCHAR(254) NOT NULL,
    department VARCHAR(100),
    position INTEGER NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'NOT_STARTED',
    assigned_by VARCHAR(254) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_review_assignments PRIMARY KEY (id),
    CONSTRAINT ck_review_assignments_round CHECK (round > 0),
    CONSTRAINT ck_review_assignments_position CHECK (position >= 1),
    CONSTRAINT ck_review_assignments_status CHECK (status IN ('NOT_STARTED', 'SUBMITTED')),
    CONSTRAINT uq_review_assignments_brief_round_reviewer UNIQUE (brief_id, round, reviewer_id),
    CONSTRAINT uq_review_assignments_brief_round_position UNIQUE (brief_id, round, position)
);

CREATE INDEX ix_review_assignments_reviewer_status ON review_assignments (reviewer_id, status);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    assignment_id BIGINT NOT NULL,
    decision VARCHAR(32) NOT NULL,
    comment VARCHAR(2000) NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_reviews PRIMARY KEY (id),
    CONSTRAINT ck_reviews_decision CHECK (
        decision IN ('RECOMMENDED', 'CHANGES_NEEDED', 'NOT_RECOMMENDED')
    ),
    CONSTRAINT uq_reviews_assignment UNIQUE (assignment_id),
    CONSTRAINT fk_reviews_assignment
        FOREIGN KEY (assignment_id) REFERENCES review_assignments (id)
);

CREATE TABLE review_follow_up_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    review_id BIGINT NOT NULL,
    note VARCHAR(1000) NOT NULL,
    created_by VARCHAR(254) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_review_follow_up_notes PRIMARY KEY (id),
    CONSTRAINT fk_review_follow_up_notes_review
        FOREIGN KEY (review_id) REFERENCES reviews (id)
);

CREATE INDEX ix_review_follow_up_notes_review_created
    ON review_follow_up_notes (review_id, created_at);

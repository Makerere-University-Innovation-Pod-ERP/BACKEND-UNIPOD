package org.unipod.unipoderpbackend.service.document;

import java.util.Arrays;
import java.util.List;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/**
 * What every printed document shows about UniPod. All values come from settings, so the
 * real address, bank details and footer can be set on the server without a code change.
 */
@Component
public class DocumentBranding {
    private final String organisationName;
    private final List<String> addressLines;
    private final String contact;
    private final List<String> bankDetails;
    private final String footer;

    public DocumentBranding(
            @Value("${documents.organisation-name:Makerere University Innovation Pod (UniPod)}") String organisationName,
            @Value("${documents.address:[Address to be confirmed]}") String address,
            @Value("${documents.contact:[Phone and email to be confirmed]}") String contact,
            @Value("${documents.bank-details:[Bank details to be confirmed]}") String bankDetails,
            @Value("${documents.footer:This document was generated by the UniPod ERP.}") String footer
    ) {
        this.organisationName = organisationName;
        this.addressLines = lines(address);
        this.contact = contact;
        this.bankDetails = lines(bankDetails);
        this.footer = footer;
    }

    private static List<String> lines(String value) {
        return Arrays.stream(value.split("\\s*\\|\\s*")).filter(line -> !line.isBlank()).toList();
    }

    public String organisationName() {
        return organisationName;
    }

    public List<String> addressLines() {
        return addressLines;
    }

    public String contact() {
        return contact;
    }

    public List<String> bankDetails() {
        return bankDetails;
    }

    public String footer() {
        return footer;
    }
}
